import time

def курс_печати():
    # Тексты для тренировки
    тексты = [
        "Привет! Это тест на скорость печати.",
        "Python — отличный язык программирования.",
        "Тренировка помогает стать быстрее и точнее.",
        "Удачи в обучении!"
    ]

    print("Добро пожаловать в курс печати на Python!")
    print("Вы будете видеть текст для набора. Постарайтесь напечатать его как можно быстрее и без ошибок.")
    input("Нажмите Enter, чтобы начать...")

    for текст in тексты:
        print("\nСледующий текст для набора:\n")
        print(текст)
        input("\nНажмите Enter, когда будете готовы начать...")

        start_time = time.time()
        ввод = input("\nВведите текст:\n")
        end_time = time.time()

        время_печати = end_time - start_time

        # Подсчет ошибок
        ошибки = 0
        for i in range(min(len(ввод), len(текст))):
            if ввод[i] != текст[i]:
                ошибки += 1
        # Если введено больше символов, считаем их как ошибки
        ошибки += abs(len(ввод) - len(текст))

        скорость_символов_в_секунду = len(ввод) / время_печати if время_печати > 0 else 0

        print(f"\nРезультаты:")
        print(f"Время: {время_печати:.2f} секунд")
        print(f"Ошибки: {ошибки}")
        print(f"Скорость набора: {скорость_символов_в_секунду:.2f} символов/секунда")
        input("Нажмите Enter для следующего текста...")

    print("\nКурс завершен! Молодец!")

if __name__ == "__main__":
    курс_печати()